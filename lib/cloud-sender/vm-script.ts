/**
 * Source of the sender script that runs ON the Boat VM (Node + playwright-core).
 * It attaches to the sender's dedicated Chrome over a local CDP port and drives real Gmail.
 *
 * Kept as a plain string so the server can upload it as-is. Rules for editing:
 * - no backticks and no "${" inside the script (it lives in a template literal);
 * - bump SENDER_SCRIPT_VERSION on every change so VMs pick up the new copy.
 *
 * Output contract: exactly one line `NXS_RESULT {json}` on stdout.
 */

export const SENDER_SCRIPT_VERSION = "5";

export const SENDER_SCRIPT_SOURCE = String.raw`// Nexuses cloud sender. Generated by Unified-portal; do not edit on the VM.
import { readFileSync } from "node:fs";
import { spawn } from "node:child_process";
import { chromium } from "playwright-core";

const VERSION = "__SENDER_VERSION__";
const EMAIL_RE = /[A-Za-z0-9._%+-]+@[A-Za-z0-9.-]+\.[A-Za-z]{2,}/;

function out(result) {
  process.stdout.write("NXS_RESULT " + JSON.stringify(result) + "\n");
}

function readArgs() {
  // Large payloads (email HTML) arrive in a file; small ones in the environment.
  const file = process.env.SENDER_ARGS_FILE || "";
  if (file) return JSON.parse(Buffer.from(readFileSync(file, "utf8").trim(), "base64").toString("utf8"));
  const raw = process.env.SENDER_ARGS_B64 || "";
  if (!raw) return {};
  return JSON.parse(Buffer.from(raw, "base64").toString("utf8"));
}

function fail(code, message) {
  const error = new Error(message || code);
  error.code = code;
  return error;
}

async function connect(port) {
  let browser;
  try {
    browser = await chromium.connectOverCDP("http://127.0.0.1:" + port, { timeout: 15000 });
  } catch (error) {
    throw fail("CDP_UNREACHABLE", String((error && error.message) || error).slice(0, 200));
  }
  const context = browser.contexts()[0];
  if (!context) throw fail("NO_BROWSER_CONTEXT");
  return { browser, context };
}

/** Reuse one Gmail tab; never pile up new ones. */
async function mailPage(context) {
  const pages = context.pages();
  let page = pages.find((p) => p.url().startsWith("https://mail.google.com/"));
  if (!page) {
    page = pages.find((p) => p.url() === "about:blank" || p.url().startsWith("chrome://newtab"));
  }
  if (!page) page = await context.newPage();
  page.on("dialog", (dialog) => dialog.accept().catch(() => {}));
  await page.bringToFront().catch(() => {});
  return page;
}

function isLoginUrl(url) {
  return /accounts\.google\.com|workspace\.google\.com|google\.com\/(intl\/[^/]+\/)?gmail\/about/.test(url);
}

async function readAccountEmail(page) {
  const title = await page.title().catch(() => "");
  let match = title.match(EMAIL_RE);
  if (match) return match[0].toLowerCase();
  const label = await page
    .evaluate(() => {
      const el = document.querySelector('a[aria-label*="@"], [role="button"][aria-label*="@"]');
      return el ? el.getAttribute("aria-label") || "" : "";
    })
    .catch(() => "");
  match = String(label).match(EMAIL_RE);
  return match ? match[0].toLowerCase() : "";
}

/** Open the inbox and report whether this profile is signed in, and as whom. */
async function cmdCheck(args) {
  const { context } = await connect(args.port);
  const page = await mailPage(context);
  await page
    .goto("https://mail.google.com/mail/u/0/#inbox", { waitUntil: "domcontentloaded", timeout: 45000 })
    .catch((error) => {
      throw fail("GMAIL_NAVIGATION_FAILED", String((error && error.message) || error).slice(0, 200));
    });
  const deadline = Date.now() + 30000;
  while (Date.now() < deadline) {
    const url = page.url();
    if (isLoginUrl(url)) return { ok: true, status: "login_required", url: url.slice(0, 160) };
    if (url.startsWith("https://mail.google.com/mail/")) {
      const email = await readAccountEmail(page);
      if (email) return { ok: true, status: "ready", email };
    }
    await page.waitForTimeout(1000);
  }
  return { ok: false, code: "GMAIL_NOT_LOADED", url: page.url().slice(0, 160) };
}

/* ---------------------------------------------------------------- Gmail send */

// Language-neutral markers where possible (attributes/classes Gmail has kept for years).
const GMAIL = {
  editor:
    'div[contenteditable="true"][g_editable="true"], div[role="textbox"][contenteditable="true"][aria-multiline="true"]',
  subject: 'input[name="subjectbox"]',
  sendButton:
    'div[role="button"].aoO, div[role="button"][data-tooltip^="Send"], div[role="button"][aria-label^="Send"]',
  sentLink: "#link_vsm",
  undoLink: "#link_undo",
  listRow: "tr.zA",
  emptyList: "td.TC",
};

// Shared with the watchdog so a timeout can say whether Send was already pressed.
const state = { stage: "start", sendPressed: false };

function norm(text) {
  return String(text || "").replace(/\s+/g, " ").trim().toLowerCase();
}

async function shot(page, name) {
  const path = "/tmp/nexuses-sender-" + name + ".jpg";
  try {
    await page.screenshot({ path, type: "jpeg", quality: 55 });
    return path;
  } catch {
    return "";
  }
}

async function ensureSignedIn(page, expectedEmail) {
  if (isLoginUrl(page.url())) throw fail("LOGIN_REQUIRED");
  if (!expectedEmail) return;
  const email = await readAccountEmail(page);
  if (email && email !== String(expectedEmail).toLowerCase()) {
    throw fail("WRONG_ACCOUNT", "Signed in as " + email);
  }
}

/** Search Sent for this recipient + subject. Returns true/false, or null if the list never loaded. */
async function findInSent(page, to, subject, days) {
  const query = "in:sent to:" + to + " newer_than:" + (days || 7) + "d";
  await page.goto("https://mail.google.com/mail/u/0/#search/" + encodeURIComponent(query), {
    waitUntil: "domcontentloaded",
    timeout: 45000,
  });
  // Let the in-app route change replace whatever list was showing before.
  await page.waitForTimeout(2500);
  const needle = norm(subject).slice(0, 60);
  const deadline = Date.now() + 20000;
  while (Date.now() < deadline) {
    if (isLoginUrl(page.url())) throw fail("LOGIN_REQUIRED");
    const seen = await page
      .evaluate(
        (sel) => {
          const rows = Array.from(document.querySelectorAll(sel.row)).filter((r) => r.offsetParent);
          const empty = Array.from(document.querySelectorAll(sel.empty)).some((e) => e.offsetParent);
          return { rows: rows.map((r) => (r.innerText || "").toLowerCase()), empty };
        },
        { row: GMAIL.listRow, empty: GMAIL.emptyList },
      )
      .catch(() => ({ rows: [], empty: false }));
    const normalizedRows = seen.rows.map((r) => r.replace(/\s+/g, " "));
    if (needle && normalizedRows.some((r) => r.includes(needle))) return true;
    if (seen.empty) return false;
    if (normalizedRows.length > 0) return false;
    await page.waitForTimeout(1000);
  }
  return null;
}

async function waitForEditor(page) {
  const editor = page.locator(GMAIL.editor).last();
  try {
    await editor.waitFor({ state: "visible", timeout: 30000 });
  } catch {
    if (isLoginUrl(page.url())) throw fail("LOGIN_REQUIRED");
    throw fail("COMPOSE_NOT_LOADED");
  }
  return editor;
}

/** To and Subject come from the compose URL; verify Gmail really put them there. */
async function verifyHeaders(page, to, subject) {
  const info = await page.evaluate(
    (sel) => {
      const subjects = Array.from(document.querySelectorAll(sel.subject)).filter((e) => e.offsetParent);
      const subjectValue = subjects.length ? subjects[subjects.length - 1].value : "";
      const emails = [];
      document.querySelectorAll("[email], [data-hovercard-id]").forEach((el) => {
        const v = el.getAttribute("email") || el.getAttribute("data-hovercard-id") || "";
        if (v.includes("@")) emails.push(v.toLowerCase());
      });
      document.querySelectorAll("input").forEach((el) => {
        const v = String(el.value || "");
        if (v.includes("@")) emails.push(v.toLowerCase());
      });
      return { subjectValue, emails };
    },
    { subject: GMAIL.subject },
  );
  if (norm(info.subjectValue) !== norm(subject)) {
    throw fail("SUBJECT_MISMATCH", "Subject shows: " + String(info.subjectValue).slice(0, 120));
  }
  const target = String(to).toLowerCase();
  if (!info.emails.some((e) => e.includes(target))) {
    throw fail("RECIPIENT_MISMATCH", "Recipient " + target + " is not in the To field");
  }
}

/** Select where the pasted body goes: everything (replace auto-signature) or the very start. */
async function selectBodyTarget(page, replaceAll) {
  const ok = await page.evaluate(
    (input) => {
      const editors = Array.from(document.querySelectorAll(input.sel)).filter((e) => e.offsetParent);
      const editor = editors[editors.length - 1];
      if (!editor) return false;
      editor.focus();
      const selection = window.getSelection();
      const range = document.createRange();
      if (input.replaceAll) {
        range.selectNodeContents(editor);
      } else {
        range.setStart(editor, 0);
        range.collapse(true);
      }
      selection.removeAllRanges();
      selection.addRange(range);
      return true;
    },
    { sel: GMAIL.editor, replaceAll: Boolean(replaceAll) },
  );
  if (!ok) throw fail("BODY_INSERT_FAILED", "No editor to paste into");
}

async function editorTextLength(page) {
  return page
    .evaluate((sel) => {
      const editors = Array.from(document.querySelectorAll(sel)).filter((e) => e.offsetParent);
      const editor = editors[editors.length - 1];
      return editor ? (editor.innerText || "").length : -1;
    }, GMAIL.editor)
    .catch(() => -1);
}

/** Put rich HTML on the X clipboard (Chrome pastes from it like a human Ctrl+V). */
function xclipHtml(html) {
  return new Promise((resolve) => {
    let child;
    try {
      child = spawn("xclip", ["-selection", "clipboard", "-t", "text/html", "-i"], {
        env: { ...process.env, DISPLAY: process.env.DISPLAY || ":0" },
        detached: true,
        stdio: ["pipe", "ignore", "ignore"],
      });
    } catch {
      resolve(false);
      return;
    }
    child.on("error", () => resolve(false));
    child.stdin.end(html, () => {
      child.unref();
      setTimeout(() => resolve(true), 400);
    });
  });
}

/** Same thing through the browser's own clipboard API (fallback). */
async function apiClipboardHtml(page, html, plain) {
  return page
    .evaluate(
      async (input) => {
        try {
          const item = new ClipboardItem({
            "text/html": new Blob([input.html], { type: "text/html" }),
            "text/plain": new Blob([input.plain], { type: "text/plain" }),
          });
          await navigator.clipboard.write([item]);
          return true;
        } catch (error) {
          return String((error && error.message) || error);
        }
      },
      { html, plain },
    )
    .catch((error) => String((error && error.message) || error));
}

/**
 * Paste our HTML into the body the way a person would (Gmail blocks direct HTML injection).
 * Tries the X clipboard first, then the browser clipboard API; each attempt is checked.
 */
async function insertBody(page, context, html, plain, replaceAll) {
  await context
    .grantPermissions(["clipboard-read", "clipboard-write"], { origin: "https://mail.google.com" })
    .catch(() => {});
  const before = await editorTextLength(page);
  const strategies = ["xclip", "clipboard_api"];
  const notes = [];
  for (const strategy of strategies) {
    const ready =
      strategy === "xclip" ? await xclipHtml(html) : await apiClipboardHtml(page, html, plain);
    if (ready !== true) {
      notes.push(strategy + ": " + String(ready));
      continue;
    }
    await selectBodyTarget(page, replaceAll);
    await page.keyboard.press("Control+V");
    await page.waitForTimeout(900);
    const after = await editorTextLength(page);
    if (after > Math.max(0, before) + 10 || (replaceAll && after > 10 && after !== before)) {
      return strategy;
    }
    notes.push(strategy + ": paste did not change the body");
  }
  throw fail("BODY_INSERT_FAILED", notes.join("; ").slice(0, 300));
}

/** Read the body back: it must contain the pitch text and the bold we expect. */
async function verifyBody(page, expectText, expectStrong) {
  const body = await page.evaluate((sel) => {
    const editors = Array.from(document.querySelectorAll(sel)).filter((e) => e.offsetParent);
    const editor = editors[editors.length - 1];
    if (!editor) return null;
    return {
      text: editor.innerText || "",
      strong: editor.querySelectorAll("b, strong").length,
    };
  }, GMAIL.editor);
  if (!body) throw fail("BODY_VERIFY_FAILED", "Editor disappeared");
  const text = norm(body.text);
  for (const fragment of expectText || []) {
    const needle = norm(fragment);
    if (needle && !text.includes(needle)) {
      throw fail("BODY_VERIFY_FAILED", "Missing text: " + needle.slice(0, 80));
    }
  }
  if (Number(expectStrong) > 0 && body.strong < Number(expectStrong)) {
    throw fail("BODY_VERIFY_FAILED", "Expected bold " + expectStrong + ", found " + body.strong);
  }
  return { chars: text.length, strong: body.strong };
}

/** After Send: Gmail shows a "View message" link (#link_vsm) carrying the message id. */
async function waitForSent(page, ms) {
  const deadline = Date.now() + ms;
  while (Date.now() < deadline) {
    const status = await page
      .evaluate(
        (sel) => {
          const link = document.querySelector(sel.link);
          const editors = Array.from(document.querySelectorAll(sel.editor)).filter((e) => e.offsetParent);
          return {
            link: link ? link.getAttribute("href") || "#" : "",
            editorOpen: editors.length > 0,
          };
        },
        { link: GMAIL.sentLink, editor: GMAIL.editor },
      )
      .catch(() => ({ link: "", editorOpen: true }));
    if (status.link) {
      const id = (status.link.match(/#[^/?]+\/([A-Za-z0-9_-]{10,})/) || [])[1] || "";
      return { confirmed: true, messageId: id, via: "view_message_link" };
    }
    if (!status.editorOpen) return { confirmed: false, editorClosed: true };
    await page.waitForTimeout(500);
  }
  return { confirmed: false, editorClosed: false };
}

async function cmdSend(args) {
  const to = String(args.to || "").trim();
  const subject = String(args.subject || "").trim();
  if (!to.includes("@") || !subject || !args.html) throw fail("BAD_ARGS");
  const { context } = await connect(args.port);
  const page = await mailPage(context);
  const t0 = Date.now();

  // Duplicate guard for retried/resumed rows.
  if (args.dupCheck) {
    state.stage = "dup_check";
    const already = await findInSent(page, to, subject, 7);
    if (already === true) return { ok: true, status: "already_sent", ms: Date.now() - t0 };
    if (already === null) throw fail("SENT_LIST_NOT_LOADED");
  }

  state.stage = "compose";
  const composeUrl =
    "https://mail.google.com/mail/u/0/?view=cm&fs=1&tf=1&to=" +
    encodeURIComponent(to) +
    "&su=" +
    encodeURIComponent(subject);
  await page.goto(composeUrl, { waitUntil: "domcontentloaded", timeout: 45000 }).catch((error) => {
    throw fail("COMPOSE_NOT_LOADED", String((error && error.message) || error).slice(0, 200));
  });
  await ensureSignedIn(page, args.expectedEmail);
  await waitForEditor(page);
  // Let Gmail finish inserting its auto-signature before we touch the body.
  await page.waitForTimeout(1500);
  await ensureSignedIn(page, args.expectedEmail);

  state.stage = "verify_headers";
  await verifyHeaders(page, to, subject);

  state.stage = "insert_body";
  const pastedWith = await insertBody(page, context, args.html, args.plain || "", args.replaceSignature);
  await page.waitForTimeout(400);

  state.stage = "verify_body";
  const body = await verifyBody(page, args.expectText, args.expectStrong);

  if (args.dryRun) {
    const screenshot = await shot(page, "dryrun");
    return { ok: true, status: "dry_run_ok", body, pastedWith, screenshot, ms: Date.now() - t0 };
  }

  // Everything checked: send.
  state.stage = "send";
  await page.locator(GMAIL.editor).last().focus();
  state.sendPressed = true;
  await page.keyboard.press("Control+Enter");
  let sent = await waitForSent(page, 12000);
  if (!sent.confirmed && !sent.editorClosed) {
    // Shortcut didn't take; click the Send button once.
    const button = page.locator(GMAIL.sendButton).last();
    if (await button.isVisible().catch(() => false)) {
      await button.click({ timeout: 5000 }).catch(() => {});
      sent = await waitForSent(page, 15000);
    }
  }
  if (sent.confirmed) {
    // Gmail holds the message during its "Undo" window; let it pass before leaving the page.
    state.stage = "undo_window";
    await page
      .locator(GMAIL.undoLink)
      .first()
      .waitFor({ state: "hidden", timeout: 35000 })
      .catch(() => {});
    await page.waitForTimeout(1500);
    // Strongest proof: the message is in Sent.
    state.stage = "verify_sent";
    const inSent = args.skipSentCheck ? null : await findInSent(page, to, subject, 1).catch(() => null);
    return {
      ok: true,
      status: "sent",
      messageId: sent.messageId,
      via: sent.via,
      inSent,
      pastedWith,
      ms: Date.now() - t0,
    };
  }

  // No link seen: prove it from the Sent folder before reporting anything.
  state.stage = "verify_sent";
  const inSent = await findInSent(page, to, subject, 1).catch(() => null);
  if (inSent === true) return { ok: true, status: "sent", via: "sent_folder", ms: Date.now() - t0 };
  const screenshot = await shot(page, "unconfirmed");
  return {
    ok: false,
    code: "SEND_UNCONFIRMED",
    sendPressed: true,
    editorClosed: Boolean(sent.editorClosed),
    screenshot,
    ms: Date.now() - t0,
  };
}

async function cmdFindSent(args) {
  const { context } = await connect(args.port);
  const page = await mailPage(context);
  const found = await findInSent(page, String(args.to || ""), String(args.subject || ""), Number(args.days) || 7);
  return { ok: found !== null, status: found === true ? "found" : found === false ? "not_found" : "unknown" };
}

const command = process.argv[2] || "";
let args = {};
try {
  args = readArgs();
} catch {
  out({ ok: false, code: "BAD_ARGS" });
  process.exit(0);
}
const watchdog = setTimeout(() => {
  out({
    ok: false,
    version: VERSION,
    code: "SCRIPT_TIMEOUT",
    stage: state.stage,
    sendPressed: state.sendPressed,
  });
  process.exit(0);
}, Number(args.timeoutMs) || 80000);

try {
  let result;
  if (command === "version") result = { ok: true, version: VERSION };
  else if (command === "check") result = await cmdCheck(args);
  else if (command === "send") result = await cmdSend(args);
  else if (command === "find_sent") result = await cmdFindSent(args);
  else result = { ok: false, code: "UNKNOWN_COMMAND", command };
  out({ version: VERSION, stage: state.stage, sendPressed: state.sendPressed, ...result });
} catch (error) {
  out({
    ok: false,
    version: VERSION,
    code: (error && error.code) || "SCRIPT_ERROR",
    message: String((error && error.message) || error).slice(0, 300),
    stage: state.stage,
    sendPressed: state.sendPressed,
  });
} finally {
  clearTimeout(watchdog);
  // Exit without browser.close(): we only detach; the user's Chrome keeps running.
  process.exit(0);
}
`.replace("__SENDER_VERSION__", SENDER_SCRIPT_VERSION);
