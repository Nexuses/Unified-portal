async function gmailThreadOpen(page, subject) {
  const needle = norm(subject).replace(/^(re|fwd?):\s*/i, "").slice(0, 50);
  return page
    .evaluate(
      (input) => {
        const h = Array.from(document.querySelectorAll(input.sel)).find((e) => e.offsetParent);
        return Boolean(h && String(h.innerText || "").replace(/\s+/g, " ").toLowerCase().includes(input.needle));
      },
      { sel: GMAIL_REPLY.threadSubject, needle },
    )
    .catch(() => false);
}

/** Open the conversation we sent (by message id, else by searching Sent). */
async function openGmailThread(page, to, subject, messageId) {
  if (messageId) {
    await page.goto("https://mail.google.com/mail/u/0/#sent/" + messageId, { waitUntil: "domcontentloaded", timeout: 45000 });
    for (let i = 0; i < 12; i += 1) {
      await page.waitForTimeout(1000);
      if (isLoginUrl(page.url())) throw fail("LOGIN_REQUIRED");
      if (await gmailThreadOpen(page, subject)) return "message_id";
    }
  }
  const query = "in:sent to:" + to + ' subject:"' + String(subject).replace(/"/g, " ") + '"';
  await page.goto("https://mail.google.com/mail/u/0/#search/" + encodeURIComponent(query), {
    waitUntil: "domcontentloaded",
    timeout: 45000,
  });
  await page.waitForTimeout(2500);
  const needle = norm(subject).slice(0, 50);
  const deadline = Date.now() + 20000;
  while (Date.now() < deadline) {
    if (isLoginUrl(page.url())) throw fail("LOGIN_REQUIRED");
    const handle = await page.evaluateHandle(
      (input) => {
        const rows = Array.from(document.querySelectorAll(input.row)).filter((r) => r.offsetParent);
        return rows.find((r) => String(r.innerText || "").replace(/\s+/g, " ").toLowerCase().includes(input.needle)) || null;
      },
      { row: GMAIL.listRow, needle },
    );
    const row = handle.asElement();
    if (row) {
      await row.click({ timeout: 5000 }).catch(() => {});
      for (let i = 0; i < 12; i += 1) {
        await page.waitForTimeout(1000);
        if (await gmailThreadOpen(page, subject)) return "search";
      }
      throw fail("THREAD_NOT_OPENED");
    }
    const empty = await page
      .evaluate((sel) => Array.from(document.querySelectorAll(sel)).some((e) => e.offsetParent), GMAIL.emptyList)
      .catch(() => false);
    if (empty) throw fail("THREAD_NOT_FOUND", "No sent email to " + to + " with that subject");
    await page.waitForTimeout(1000);
  }
  throw fail("THREAD_NOT_FOUND", "Sent list didn't load");
}

/** Recipients shown in the open reply box (null when they can't be read). */
async function gmailReplyRecipients(page) {
  return page
    .evaluate((input) => {
      const editors = Array.from(document.querySelectorAll(input.editor)).filter((e) => e.offsetParent);
      let node = editors[editors.length - 1];
      for (let depth = 0; node && depth < 25; depth += 1) {
        node = node.parentElement;
        if (!node) break;
        if (node.querySelector(input.body)) return null; // reached the conversation: give up
        const found = Array.from(node.querySelectorAll("[email]"))
          .map((e) => String(e.getAttribute("email") || "").toLowerCase())
          .filter((e) => e.includes("@"));
        if (found.length) return found;
      }
      return null;
    }, { editor: GMAIL.editor, body: GMAIL_REPLY.messageBody })
    .catch(() => null);
}

async function gmailThreadHasText(page, needle) {
  const want = norm(needle).slice(0, 50);
  if (!want) return false;
  return page
    .evaluate(
      (input) =>
        Array.from(document.querySelectorAll(input.sel)).some((e) =>
          String(e.innerText || "").replace(/\s+/g, " ").toLowerCase().includes(input.want),
        ),
      { sel: GMAIL_REPLY.messageBody, want },
    )
    .catch(() => false);
}

async function cmdReplyGmail(args) {
  const to = String(args.to || "").trim().toLowerCase();
  const subject = String(args.subject || "").trim();
  if (!to.includes("@") || !subject || !args.html) throw fail("BAD_ARGS");
  const { context } = await connect(args.port);
  const page = await mailPage(context);
  const t0 = Date.now();

  state.stage = "open_thread";
  await page.goto("https://mail.google.com/mail/u/0/#inbox", { waitUntil: "domcontentloaded", timeout: 45000 }).catch(() => {});
  await page.waitForTimeout(1500);
  await ensureSignedIn(page, args.expectedEmail);
  const openedBy = await openGmailThread(page, to, subject, String(args.messageId || ""));

  // Retry after an unclear send: if our text is already in the thread, it went out.
  if (args.dupCheck && (args.expectText || [])[0] && (await gmailThreadHasText(page, args.expectText[0]))) {
    return { ok: true, status: "already_sent", openedBy, ms: Date.now() - t0 };
  }

  state.stage = "reply";
  let clicked = false;
  for (const sel of GMAIL_REPLY.replyButtons) {
    const button = page.locator(sel).last();
    if (await button.isVisible().catch(() => false)) {
      await button.click({ timeout: 5000 }).catch(() => {});
      clicked = true;
      break;
    }
  }
  if (!clicked) throw fail("REPLY_BUTTON_MISSING");
  await waitForEditor(page);
  await page.waitForTimeout(1500);

  state.stage = "verify_headers";
  const recipients = await gmailReplyRecipients(page);
  if (recipients && !recipients.some((e) => e.includes(to))) {
    throw fail("RECIPIENT_MISMATCH", "Reply would go to " + recipients.join(", ").slice(0, 120));
  }

  state.stage = "insert_body";
  const pastedWith = await insertBody(page, context, args.html, args.plain || "", args.replaceSignature);
  await page.waitForTimeout(400);
  state.stage = "verify_body";
  const body = await verifyBody(page, args.expectText, args.expectStrong);

  if (args.dryRun) {
    const screenshot = await shot(page, "reply-dryrun");
    const discard = page.locator(GMAIL_REPLY.discard).last();
    if (await discard.isVisible().catch(() => false)) await discard.click().catch(() => {});
    return { ok: true, status: "dry_run_ok", body, pastedWith, openedBy, toVerified: Boolean(recipients), screenshot, ms: Date.now() - t0 };
  }

  state.stage = "send";
  await page.locator(GMAIL.editor).last().focus();
  state.sendPressed = true;
  await page.keyboard.press("Control+Enter");
  let sent = await waitForSent(page, 12000);
  if (!sent.confirmed && !sent.editorClosed) {
    const button = page.locator(GMAIL.sendButton).last();
    if (await button.isVisible().catch(() => false)) {
      await button.click({ timeout: 5000 }).catch(() => {});
      sent = await waitForSent(page, 15000);
    }
  }
  state.stage = "undo_window";
  await page.locator(GMAIL.undoLink).first().waitFor({ state: "hidden", timeout: 35000 }).catch(() => {});
  await page.waitForTimeout(2000);
  state.stage = "verify_sent";
  const inThread = await gmailThreadHasText(page, (args.expectText || [])[0] || "");
  if (sent.confirmed || inThread) {
    return { ok: true, status: "sent", via: sent.confirmed ? sent.via : "thread", messageId: sent.messageId, inThread, openedBy, toVerified: Boolean(recipients), pastedWith, ms: Date.now() - t0 };
  }
  const screenshot = await shot(page, "reply-unconfirmed");
  return { ok: false, code: "SEND_UNCONFIRMED", sendPressed: true, editorClosed: Boolean(sent.editorClosed), screenshot, ms: Date.now() - t0 };
}

