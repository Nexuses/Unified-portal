/**
 * Read a Google Sheet as CSV using this Chrome's Google sign-in (works for private sheets the
 * sender can open). Writes the CSV to args.outPath; the server reads it back in chunks.
 */
async function cmdReadSheet(args) {
  const url = String(args.sheetUrl || "");
  const id = (url.match(/spreadsheets\/d\/([a-zA-Z0-9_-]+)/) || [])[1];
  if (!id) throw fail("BAD_SHEET_URL");
  const gid = (url.match(/[#&?]gid=(\d+)/) || [])[1] || "";
  const { context } = await connect(args.port);
  const notes = [];
  let text = "";
  let how = "";

  // 1) Same export Google uses for "Download as CSV", with this profile's cookies.
  const exportUrl =
    "https://docs.google.com/spreadsheets/d/" + id + "/export?format=csv" + (gid ? "&gid=" + gid : "");
  try {
    const res = await context.request.get(exportUrl, { timeout: 45000, maxRedirects: 10 });
    const type = String(res.headers()["content-type"] || "");
    if (res.ok() && !/text\/html/i.test(type)) {
      text = await res.text();
      how = "export";
    } else {
      notes.push("export " + res.status() + " " + type.slice(0, 40));
    }
  } catch (error) {
    notes.push("export error " + String((error && error.message) || error).slice(0, 120));
  }

  // 2) Fallback: open the sheet in a tab and fetch the CSV from inside docs.google.com.
  if (!text) {
    const page = await context.newPage();
    try {
      await page.goto("https://docs.google.com/spreadsheets/d/" + id + "/edit" + (gid ? "#gid=" + gid : ""), {
        waitUntil: "domcontentloaded",
        timeout: 45000,
      });
      const landed = page.url();
      if (isLoginUrl(landed)) throw fail("LOGIN_REQUIRED");
      if (!/docs\.google\.com\/spreadsheets/.test(landed)) {
        throw fail("SHEET_ACCESS_DENIED", "Landed on " + landed.slice(0, 120));
      }
      const fetched = await page.evaluate(async (input) => {
        const q =
          "/spreadsheets/d/" + input.id + "/gviz/tq?tqx=out:csv&headers=1" + (input.gid ? "&gid=" + input.gid : "");
        const res = await fetch(q, { credentials: "include" });
        const type = res.headers.get("content-type") || "";
        return { ok: res.ok, status: res.status, type, body: await res.text() };
      }, { id, gid });
      if (fetched.ok && !/text\/html/i.test(fetched.type)) {
        text = fetched.body;
        how = "gviz";
      } else {
        notes.push("gviz " + fetched.status + " " + String(fetched.type).slice(0, 40));
      }
    } finally {
      await page.close().catch(() => {});
    }
  }

  if (!text.trim()) throw fail("SHEET_ACCESS_DENIED", notes.join("; ").slice(0, 300));
  const { writeFileSync } = await import("node:fs");
  writeFileSync(String(args.outPath), text, "utf8");
  return { ok: true, status: "read", how, bytes: Buffer.byteLength(text, "utf8"), notes };
}

