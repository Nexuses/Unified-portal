const EMAIL_ANY_RE = /[A-Za-z0-9._%+-]+@[A-Za-z0-9.-]+\.[A-Za-z]{2,}/g;

/** Run a Gmail search and return the visible result rows (participant emails + text). */
async function gmailSearchRows(page, query) {
  await page.goto("https://mail.google.com/mail/u/0/#search/" + encodeURIComponent(query), {
    waitUntil: "domcontentloaded",
    timeout: 45000,
  });
  await page.waitForTimeout(2500);
  const deadline = Date.now() + 15000;
  while (Date.now() < deadline) {
    if (isLoginUrl(page.url())) throw fail("LOGIN_REQUIRED");
    const seen = await page
      .evaluate(
        (sel) => {
          const rows = Array.from(document.querySelectorAll(sel.row))
            .filter((r) => r.offsetParent)
            .map((r) => ({
              emails: Array.from(r.querySelectorAll("[email]")).map((e) => String(e.getAttribute("email") || "").toLowerCase()),
              text: String(r.innerText || ""),
            }));
          const empty = Array.from(document.querySelectorAll(sel.empty)).some((e) => e.offsetParent);
          return { rows, empty };
        },
        { row: GMAIL.listRow, empty: GMAIL.emptyList },
      )
      .catch(() => ({ rows: [], empty: false }));
    if (seen.rows.length || seen.empty) return seen.rows;
    await page.waitForTimeout(1000);
  }
  return null;
}

async function scanGmailInbox(page, targets, since) {
  const replied = new Set();
  const bounced = new Set();
  const targetSet = new Set(targets);
  for (let i = 0; i < targets.length; i += 20) {
    const batch = targets.slice(i, i + 20);
    const query = "in:inbox {" + batch.map((e) => "from:" + e).join(" ") + "}" + (since ? " after:" + since : "");
    const rows = await gmailSearchRows(page, query);
    if (rows === null) throw fail("INBOX_NOT_LOADED");
    for (const row of rows) {
      for (const email of row.emails) if (batch.includes(email)) replied.add(email);
    }
  }
  const bounceRows = await gmailSearchRows(
    page,
    "{from:mailer-daemon from:postmaster}" + (since ? " after:" + since : ""),
  );
  const bounceDetails = [];
  for (const row of bounceRows || []) {
    for (const email of String(row.text).toLowerCase().match(EMAIL_ANY_RE) || []) {
      if (!targetSet.has(email) || bounced.has(email)) continue;
      bounced.add(email);
      bounceDetails.push({ email: email, reason: bounceReasonFrom(row.text) });
    }
  }
  return { replied: Array.from(replied), bounced: Array.from(bounced), bounceDetails: bounceDetails };
}

/** The useful part of a bounce notice row: why it failed, in one short line. */
function bounceReasonFrom(text) {
  const flat = String(text || "").replace(/\s+/g, " ").trim();
  const known = flat.match(
    /(address not found|address couldn.t be found|user unknown|no such user|mailbox (?:unavailable|full|not found)|recipient (?:address )?rejected|does not exist|domain (?:not found|couldn.t be found)|message (?:blocked|rejected)|over quota|access denied|5\.\d\.\d+[^.]{0,80})/i,
  );
  if (known) {
    const at = flat.toLowerCase().indexOf(known[0].toLowerCase());
    return flat.slice(Math.max(0, at - 20), at + 180).trim();
  }
  return flat.replace(/^(mail delivery subsystem|microsoft outlook|postmaster|mailer-daemon)\s*/i, "").slice(0, 200);
}

/** Outlook on the web: run a search and return how many rows show and the first row's text. */
async function outlookSearchFirst(page, query) {
  const box = page.locator('#topSearchInput, input[aria-label="Search"], input[placeholder*="Search"]').first();
  if (!(await box.isVisible().catch(() => false))) throw fail("OUTLOOK_SEARCH_UNAVAILABLE");
  await box.click({ timeout: 5000 });
  await box.fill(query);
  await page.keyboard.press("Enter");
  await page.waitForTimeout(4500);
  const seen = await page
    .evaluate((sel) => {
      const rows = Array.from(document.querySelectorAll(sel)).filter((r) => r.offsetParent);
      return { count: rows.length, text: rows.length ? String(rows[0].innerText || "") : "" };
    }, OUTLOOK.listRow)
    .catch(() => ({ count: 0, text: "" }));
  await page.keyboard.press("Escape").catch(() => {});
  return seen;
}

/** Outlook on the web: one search per address (results show names, so match by query). */
async function outlookSearchCount(page, query) {
  const box = page.locator('#topSearchInput, input[aria-label="Search"], input[placeholder*="Search"]').first();
  if (!(await box.isVisible().catch(() => false))) throw fail("OUTLOOK_SEARCH_UNAVAILABLE");
  await box.click({ timeout: 5000 });
  await box.fill(query);
  await page.keyboard.press("Enter");
  await page.waitForTimeout(4500);
  const count = await page
    .evaluate((sel) => Array.from(document.querySelectorAll(sel)).filter((r) => r.offsetParent).length, OUTLOOK.listRow)
    .catch(() => 0);
  await page.keyboard.press("Escape").catch(() => {});
  return count;
}

async function scanOutlookInbox(page, targets) {
  const replied = [];
  const bounced = [];
  const bounceDetails = [];
  for (const email of targets) {
    if ((await outlookSearchCount(page, "from:" + email)) > 0) replied.push(email);
    const bounce = await outlookSearchFirst(page, "Undeliverable " + email);
    if (bounce.count > 0) {
      bounced.push(email);
      bounceDetails.push({ email: email, reason: bounceReasonFrom(bounce.text) });
    }
  }
  return { replied, bounced, bounceDetails };
}

async function cmdInboxScan(args) {
  const targets = Array.from(
    new Set((args.emails || []).map((e) => String(e).trim().toLowerCase()).filter((e) => e.includes("@"))),
  );
  if (!targets.length) return { ok: true, status: "scanned", replied: [], bounced: [] };
  const outlook = args.provider === "outlook";
  const { context } = await connect(args.port);
  const page = await mailPage(context, outlook ? "outlook" : "gmail");
  state.stage = "inbox_scan";
  if (outlook) {
    if (!isOutlookUrl(page.url())) await gotoOutlookInbox(page);
    await page.waitForTimeout(2000);
    if (isLoginUrl(page.url())) throw fail("LOGIN_REQUIRED");
    return { ok: true, status: "scanned", ...(await scanOutlookInbox(page, targets)) };
  }
  return { ok: true, status: "scanned", ...(await scanGmailInbox(page, targets, String(args.since || ""))) };
}

