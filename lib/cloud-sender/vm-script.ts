async function cmdCheckOutlook(args) {
  const { context } = await connect(args.port);
  const page = await mailPage(context, "outlook");
  await gotoOutlookInbox(page);
  const deadline = Date.now() + 45000;
  while (Date.now() < deadline) {
    const url = page.url();
    if (isLoginUrl(url)) return { ok: true, status: "login_required", url: url.slice(0, 160) };
    if (isOutlookUrl(url) && /\/mail/.test(url)) {
      const email = await readOutlookEmail(page);
      if (email) return { ok: true, status: "ready", email, host: new URL(url).host };
    }
    await page.waitForTimeout(1500);
  }
  return { ok: false, code: "OUTLOOK_NOT_LOADED", url: page.url().slice(0, 160) };
}

/** Find a sent message by subject in Sent Items (first page is enough: we look right after sending). */
async function findInSentOutlook(page, to, subject) {
  await page.goto(outlookBase(page) + "/sentitems", { waitUntil: "domcontentloaded", timeout: 60000 });
  await page.waitForTimeout(3000);
  const needle = norm(subject).slice(0, 60);
  const deadline = Date.now() + 25000;
  while (Date.now() < deadline) {
    if (isLoginUrl(page.url())) throw fail("LOGIN_REQUIRED");
    const rows = await page
      .evaluate((sel) => {
        return Array.from(document.querySelectorAll(sel))
          .filter((r) => r.offsetParent)
          .map((r) => ((r.getAttribute("aria-label") || "") + " " + (r.innerText || "")).toLowerCase());
      }, OUTLOOK.listRow)
      .catch(() => []);
    const normalized = rows.map((r) => r.replace(/\s+/g, " "));
    if (needle && normalized.some((r) => r.includes(needle))) return true;
    if (normalized.length > 0) return false;
    await page.waitForTimeout(1500);
  }
  return null;
}

async function outlookEditorOpen(page) {
  return page
    .evaluate((sel) => Array.from(document.querySelectorAll(sel)).some((e) => e.offsetParent), OUTLOOK.editor)
    .catch(() => true);
}

async function cmdSendOutlook(args) {
  const to = String(args.to || "").trim();
  const subject = String(args.subject || "").trim();
  if (!to.includes("@") || !subject || !args.html) throw fail("BAD_ARGS");
  const { context } = await connect(args.port);
  const page = await mailPage(context, "outlook");
  const t0 = Date.now();

  state.stage = "open_outlook";
  if (!isOutlookUrl(page.url())) await gotoOutlookInbox(page);
  await page.waitForTimeout(1500);
  if (isLoginUrl(page.url())) throw fail("LOGIN_REQUIRED");
  if (args.expectedEmail) {
    const email = await readOutlookEmail(page);
    if (email && email !== String(args.expectedEmail).toLowerCase()) {
      throw fail("WRONG_ACCOUNT", "Signed in as " + email);
    }
  }

  if (args.dupCheck) {
    state.stage = "dup_check";
    const already = await findInSentOutlook(page, to, subject);
    if (already === true) return { ok: true, status: "already_sent", ms: Date.now() - t0 };
    if (already === null) throw fail("SENT_LIST_NOT_LOADED");
  }

  state.stage = "compose";
  const composeUrl =
    outlookBase(page) + "/deeplink/compose?to=" + encodeURIComponent(to) + "&subject=" + encodeURIComponent(subject);
  await page.goto(composeUrl, { waitUntil: "domcontentloaded", timeout: 60000 }).catch((error) => {
    throw fail("COMPOSE_NOT_LOADED", String((error && error.message) || error).slice(0, 200));
  });
  const editor = page.locator(OUTLOOK.editor).last();
  try {
    await editor.waitFor({ state: "visible", timeout: 40000 });
  } catch {
    if (isLoginUrl(page.url())) throw fail("LOGIN_REQUIRED");
    throw fail("COMPOSE_NOT_LOADED");
  }
  // Outlook inserts the auto-signature a moment after the editor appears.
  await page.waitForTimeout(2500);

  state.stage = "verify_headers";
  const headers = await page.evaluate(
    (input) => {
      const inputs = Array.from(document.querySelectorAll("input")).filter((e) => e.offsetParent);
      const subjectOk = inputs.some((e) => String(e.value || "").trim().toLowerCase() === input.subject);
      const target = input.to;
      let toOk = false;
      document.querySelectorAll("[aria-label], [title]").forEach((el) => {
        const t = ((el.getAttribute("aria-label") || "") + " " + (el.getAttribute("title") || "")).toLowerCase();
        if (t.includes(target)) toOk = true;
      });
      if (!toOk) {
        document.querySelectorAll('[role="button"], [role="listitem"], [role="option"], span').forEach((el) => {
          if (el.offsetParent && String(el.textContent || "").toLowerCase().includes(target)) toOk = true;
        });
      }
      return { subjectOk, toOk };
    },
    { subject: norm(subject), to: to.toLowerCase() },
  );
  if (!headers.subjectOk) throw fail("SUBJECT_MISMATCH");
  if (!headers.toOk) throw fail("RECIPIENT_MISMATCH", "Recipient " + to + " is not in the To field");

  state.stage = "insert_body";
  const pastedWith = await insertBodyGeneric(page, context, OUTLOOK.editor, args.html, args.plain || "", args.replaceSignature);

  state.stage = "verify_body";
  const body = await verifyBodyGeneric(page, OUTLOOK.editor, args.expectText, args.expectStrong);

  if (args.dryRun) {
    const screenshot = await shot(page, "dryrun-outlook");
    return { ok: true, status: "dry_run_ok", body, pastedWith, screenshot, ms: Date.now() - t0 };
  }

  state.stage = "send";
  state.sendPressed = true;
  let sendButton = null;
  for (const sel of OUTLOOK.sendButtons) {
    const candidate = page.locator(sel).first();
    if (await candidate.isVisible().catch(() => false)) {
      sendButton = candidate;
      break;
    }
  }
  if (sendButton) {
    await sendButton.click({ timeout: 8000 });
  } else {
    await page.locator(OUTLOOK.editor).last().focus();
    await page.keyboard.press("Control+Enter");
    // First Ctrl+Enter may ask to confirm the shortcut: accept it.
    await page.waitForTimeout(1500);
    const confirm = page.locator('div[role="dialog"] button.ms-Button--primary, div[role="dialog"] button[class*="primary"]').first();
    if (await confirm.isVisible().catch(() => false)) await confirm.click().catch(() => {});
  }
  // What is on screen right after Send (dialogs/alerts block a send silently).
  await page.waitForTimeout(3000);
  const afterSend = await page
    .evaluate(() => {
      const vis = (e) => Boolean(e.offsetParent) || getComputedStyle(e).position === "fixed";
      const text = (e) => String(e.innerText || "").replace(/\s+/g, " ").trim().slice(0, 240);
      const dialogs = Array.from(document.querySelectorAll('[role="dialog"], [role="alertdialog"]')).filter(vis).map(text).filter(Boolean).slice(0, 3);
      const alerts = Array.from(document.querySelectorAll('[role="alert"], [role="status"], [aria-live="assertive"], [aria-live="polite"]')).filter(vis).map(text).filter(Boolean).slice(0, 4);
      return { dialogs, alerts, url: location.href.slice(0, 120) };
    })
    .catch(() => ({ dialogs: [], alerts: [], url: "" }));
  const sensitivity = await handleOutlookSensitivity(page, args.sensitivityLabel);
  if (sensitivity.blocked) {
    // The dialog stops the send entirely, so nothing went out.
    state.sendPressed = false;
    return {
      ok: false,
      code: sensitivity.code,
      labels: sensitivity.labels,
      sendPressed: false,
      ms: Date.now() - t0,
    };
  }
  const closeBy = Date.now() + 22000;
  let closed = false;
  while (Date.now() < closeBy) {
    if (!(await outlookEditorOpen(page))) {
      closed = true;
      break;
    }
    await page.waitForTimeout(500);
  }
  // Outlook may hold mail for its "undo send" delay (up to 10 s).
  await page.waitForTimeout(12000);
  state.stage = "verify_sent";
  const inSent = await findInSentOutlook(page, to, subject).catch(() => null);
  if (inSent === true) {
    return {
      ok: true,
      status: "sent",
      via: closed ? "compose_closed" : "sent_folder",
      inSent,
      pastedWith,
      sensitivityLabel: sensitivity.label || undefined,
      ms: Date.now() - t0,
    };
  }
  const screenshot = await shot(page, "unconfirmed-outlook");
  return {
    ok: false,
    code: "SEND_UNCONFIRMED",
    sendPressed: true,
    editorClosed: closed,
    usedButton: Boolean(sendButton),
    afterSend,
    screenshot,
    ms: Date.now() - t0,
  };
}

/**
 * Organisations can require a sensitivity label before Send. Outlook then shows an
 * "Add sensitivity label" dialog and sends nothing until one is chosen. Pick the sender's
 * configured label; with none configured, report the available labels and send nothing.
 */
async function handleOutlookSensitivity(page, wanted) {
  const dialog = page.locator('[role="dialog"], [role="alertdialog"]').filter({ hasText: /sensitivity/i }).last();
  if (!(await dialog.isVisible().catch(() => false))) return { handled: false };
  const opener = dialog.locator('button, [role="button"], [role="combobox"]').filter({ hasText: /label/i }).first();
  await opener.click({ timeout: 5000 }).catch(() => {});
  await page.waitForTimeout(900);
  const optionSel = '[role="menuitem"], [role="menuitemradio"], [role="menuitemcheckbox"], [role="option"]';
  const labels = (await page.locator(optionSel).allInnerTexts().catch(() => []))
    .map((t) => String(t).replace(/\s+/g, " ").trim())
    .filter((t) => t && t.length <= 80);
  const unique = Array.from(new Set(labels));
  const target = String(wanted || "").trim().toLowerCase();
  const match =
    unique.find((t) => t.toLowerCase() === target) ||
    unique.find((t) => target && t.toLowerCase().startsWith(target));
  if (!target || !match) {
    await page.keyboard.press("Escape").catch(() => {});
    await dialog.locator("button").filter({ hasText: /^\s*cancel\s*$/i }).first().click({ timeout: 3000 }).catch(() => {});
    return { handled: true, blocked: true, code: target ? "SENSITIVITY_LABEL_NOT_FOUND" : "SENSITIVITY_LABEL_REQUIRED", labels: unique };
  }
  await page.locator(optionSel).filter({ hasText: match }).first().click({ timeout: 5000 });
  await page.waitForTimeout(700);
  const confirm = dialog.locator("button").filter({ hasText: /^\s*send\s*$/i }).first();
  await confirm.click({ timeout: 5000 });
  return { handled: true, blocked: false, label: match };
}

