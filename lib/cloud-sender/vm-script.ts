/**
 * Bring this sender's Chrome window to the front. Each sender has its own Chrome; a new one
 * otherwise opens behind another sender's window and the person signing in never sees it.
 */
async function cmdFocus(args) {
  const { context } = await connect(args.port);
  const outlook = args.provider === "outlook";
  const pages = context.pages();
  const mine = (u) => (outlook ? isOutlookUrl(u) : u.startsWith("https://mail.google.com/"));
  const page =
    pages.find((p) => mine(p.url())) ||
    pages.find((p) => isLoginUrl(p.url())) ||
    pages.find((p) => /^https?:/.test(p.url())) ||
    pages[0] ||
    (await context.newPage());
  let raised = false;
  try {
    const session = await context.newCDPSession(page);
    const info = await session.send("Browser.getWindowForTarget");
    await session.send("Browser.setWindowBounds", { windowId: info.windowId, bounds: { windowState: "minimized" } });
    await page.waitForTimeout(400);
    await session.send("Browser.setWindowBounds", { windowId: info.windowId, bounds: { windowState: "normal" } });
    raised = true;
  } catch (e) {}
  await page.bringToFront().catch(() => {});
  return { ok: true, status: "focused", raised, url: page.url().slice(0, 160) };
}

